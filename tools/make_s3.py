"""Generate firmware/chassis_esp32s3 from firmware/chassis_esp32 (single source of truth).
Run from the repo root: python3 tools/make_s3.py"""
src = open("firmware/chassis_esp32/chassis_esp32.ino").read()
rep = [
 ("-> ESP32 DevKit ->", "-> ESP32-S3-DevKitC-1 ->"),
 ("""// Speed out: ESP32 DAC (GPIO25 left, GPIO26 right) -> controller speed/VR/throttle input (0..3.3 V).
// DIR out:   GPIO27 left, GPIO14 right -> 2N7000 gate -> pulls controller DIR pins to GND.""",
  """// ESP32-S3 has NO DAC -> speed is 20 kHz PWM + RC filter (4.7k + 4.7uF) -> controller speed input (0..3.3 V).
// RC in:     GPIO4 = CH1, GPIO5 = CH2, GPIO6 = CH3, GPIO18 = CH4 (turtle/rabbit)
// Speed out: GPIO7 left, GPIO15 right (PWM -> filter)
// DIR out:   GPIO16 left, GPIO17 right -> 2N7000 gate -> pulls controller DIR pins to GND
// Battery:   GPIO1 = total, GPIO2 = middle (dividers 100k/6.8k)
// Needs Arduino-ESP32 core 3.x. GENERATED by tools/make_s3.py - edit chassis_esp32.ino instead."""),
 ("D36 = total, D39 = middle", "GPIO1 = total, GPIO2 = middle"),
 ("const int PIN_CH1 = 34;   // steering   (input-only pin, fine)", "const int PIN_CH1 = 4;    // steering"),
 ("const int PIN_CH2 = 35;   // throttle", "const int PIN_CH2 = 5;    // throttle"),
 ("const int PIN_CH3 = 32;   // arm switch", "const int PIN_CH3 = 6;    // arm switch"),
 ("const int PIN_CH4 = 33;   // turtle / rabbit switch", "const int PIN_CH4 = 18;   // turtle / rabbit switch"),
 ("const int PIN_SPD_L = 25; // DAC1", "const int PIN_SPD_L = 7;  // PWM left"),
 ("const int PIN_SPD_R = 26; // DAC2", "const int PIN_SPD_R = 15; // PWM right"),
 ("const int PIN_DIR_L = 27;", "const int PIN_DIR_L = 16;"),
 ("const int PIN_DIR_R = 14;", "const int PIN_DIR_R = 17;\nconst int PWM_FREQ = 20000, PWM_BITS = 10;"),
 ("const int PIN_VBAT = 36;  // VP,", "const int PIN_VBAT = 1;   // ADC1_CH0,"),
 ("const int PIN_VMID = 39;  // VN,", "const int PIN_VMID = 2;   // ADC1_CH1,"),
 ("const float V_TOP      = 3.20f; // max DAC voltage", "const float V_TOP      = 3.20f; // max filtered PWM voltage"),
 ("dacWrite(s.spdPin, (int)(v / 3.3f * 255.0f));", "ledcWrite(s.spdPin, (uint32_t)(v / 3.3f * 1023.0f));"),
 ("  pinMode(PIN_DIR_L, OUTPUT); pinMode(PIN_DIR_R, OUTPUT);\n",
  "  pinMode(PIN_DIR_L, OUTPUT); pinMode(PIN_DIR_R, OUTPUT);\n  ledcAttach(PIN_SPD_L, PWM_FREQ, PWM_BITS);\n  ledcAttach(PIN_SPD_R, PWM_FREQ, PWM_BITS);\n"),
]
for a, b in rep:
    assert a in src, "pattern not found: " + a[:60]
    src = src.replace(a, b)
assert "dacWrite" not in src
open("firmware/chassis_esp32s3/chassis_esp32s3.ino", "w").write(src)
print("chassis_esp32s3.ino generated")
